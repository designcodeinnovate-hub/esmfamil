def words_for(category: str, letter: str):
    """لیست کلماتی که با حرف مشخص شروع می‌شوند را برگردان."""
    cat = WORD_DB.get(category, {})
    # اگر دسته پیدا نشد، از همه‌ی کلمات استفاده کن
    if not cat:
        out = []
        for c in WORD_DB.values():
            out.extend(c.get(letter, []))
        return out
    return cat.get(letter, [])


def is_valid_word(word: str, category: str, letter: str) -> bool:
    """آیا کلمه در دیتابیس برای این دسته و حرف وجود دارد؟"""
    if not word:
        return False
    w = word.strip().replace("\u200c", "").replace(" ", "")
    if not w or w[0] != letter:
        return False
    candidates = words_for(category, letter)
    normalized = [c.replace("\u200c", "").replace(" ", "") for c in candidates]
    return w in normalized or w.lower() in [c.lower() for c in normalized]